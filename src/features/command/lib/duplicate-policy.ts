/**
 * 중복 등록을 **던져서** 알릴지, 경고만 남기고 먼저 등록된 쪽을 지킬지 정한다.
 *
 * 던지는 선택 자체는 옳다: 같은 조합·같은 id 에 두 등록이 붙으면 하나가 조용히 이기고, 어느 쪽이
 * 이기는지는 마운트 순서라는 보이지 않는 값에 달린다. 그 상태로 배포되면 "가끔 안 돼요" 라는
 * 재현 불가 버그가 된다.
 *
 * 그런데 이 등록은 전부 `useEffect` 안에서 일어나고, React 는 거기서 나온 예외를 **루트까지**
 * 올려 보낸다. 지금 이 레포에는 그것을 받을 곳이 없다 —
 * `grep -rn 'componentDidCatch\|ErrorBoundary\|getDerivedStateFromError' src/` 가 **0건**이다.
 * 즉 프로덕션에서 중복이 한 번 생기면 `#root` 가 통째로 비어 **하얀 화면**이 된다. 실수로 화면
 * 하나가 안 되는 것과 앱 전체가 사라지는 것은 다른 사고다.
 *
 * 그래서 대상을 나눈다.
 * - 개발·테스트: 던진다. 중복은 사용자 입력과 무관하게 결정적이라 마운트하는 순간 항상 터지고,
 *   `pnpm test` 와 `pnpm dev` 에서 100% 잡힌다. 여기서 잡는 것이 이 예외의 존재 이유다.
 * - 프로덕션: `console.error` 로 남기고 **먼저 등록된 쪽을 유지**한다. 조용한 무시보다 낫고(기록이
 *   남는다) 하얀 화면보다 낫다. 순서 의존은 남지만 "먼저 이긴다" 로 **결정적**이다.
 *
 * 앱 셸 에러 바운더리가 생기면(T-20) 이 갈래를 지우고 항상 던지는 쪽으로 되돌려도 된다.
 */

/** 지금 실행 환경에서 중복 등록이 예외여야 하는가. */
export function throwsOnDuplicate(): boolean {
  return process.env.NODE_ENV !== 'production';
}

/** 던지지 않기로 한 판에서 남기는 기록. 두 레지스트리가 같은 문구를 쓴다. */
export function reportDuplicate(error: Error): void {
  console.error(`[Tasky] ${error.message} 먼저 등록된 쪽을 유지합니다.`);
}
