#!/usr/bin/env bash
# 읽기 조건: check-author.sh 의 --body-file 예외(PR 본문 말미 플랫폼 서명 한 줄)를 바꾸거나 이 검사가 실패했을 때.
# 예외가 "마지막 줄이 정확히 그 서명일 때만" 열리고, 그 밖의 AI 흔적은 그대로 잡히는지 확인한다.
set -uo pipefail

ROOT="$(git rev-parse --show-toplevel)"
TMP="$(mktemp -d "${TMPDIR:-/tmp}/check-author-body.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
fail_count=0

SIG='_Generated by [Claude Code](https://claude.ai/code/session_abc123)_'

# expect <ok|fail> <이름> <본문>
expect() {
  local want="$1" name="$2" body="$3" f="$TMP/body.txt" rc
  printf '%s' "$body" > "$f"
  bash "$ROOT/scripts/check-author.sh" --body-file "$f" >/dev/null 2>&1
  rc=$?
  if { [ "$want" = ok ] && [ "$rc" -ne 0 ]; } || { [ "$want" = fail ] && [ "$rc" -eq 0 ]; }; then
    echo "FAIL: $name (기대 $want, rc=$rc)" >&2
    fail_count=$((fail_count + 1))
  fi
}

expect ok   "서명 없는 본문"                 $'요약\n\n- 변경'
expect ok   "말미 서명(구분선 포함)"          $'요약\n\n---\n'"$SIG"
expect ok   "말미 서명(구분선 없음·끝 빈 줄)"  $'요약\n'"$SIG"$'\n\n'
expect fail "서명이 본문 중간"                $'요약\n'"$SIG"$'\n\n뒷글'
expect fail "다른 형태의 말미 서명"            $'요약\n\n---\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'
expect fail "말미 서명 + 본문 중간 트레일러"  $'Co-Authored-By: Claude <noreply@anthropic.com>\n\n---\n'"$SIG"
expect fail "서명 줄에 글자가 더 붙음"        $'요약\n\n---\n'"$SIG"' 추가'
expect fail "세션 URL 단독"                  $'요약\nhttps://claude.ai/code/session_abc123'

if [ "$fail_count" -ne 0 ]; then
  echo "FAIL: --body-file 예외 검사 $fail_count 건 실패" >&2
  exit 1
fi
echo "OK: --body-file 예외 검사 통과"
